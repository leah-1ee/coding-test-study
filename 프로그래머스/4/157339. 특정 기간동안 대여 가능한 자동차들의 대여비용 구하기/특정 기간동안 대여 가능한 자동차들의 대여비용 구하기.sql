SELECT A.CAR_ID, A.CAR_TYPE, TRUNCATE(A.DAILY_FEE * 30 * (1 - C.DISCOUNT_RATE / 100), 0) AS FEE
FROM CAR_RENTAL_COMPANY_CAR A
JOIN CAR_RENTAL_COMPANY_DISCOUNT_PLAN C ON A.CAR_TYPE = C.CAR_TYPE AND C.DURATION_TYPE = '30일 이상'
WHERE A.CAR_TYPE IN ('세단', 'SUV') 
AND NOT EXISTS (
    SELECT 1
    FROM CAR_RENTAL_COMPANY_RENTAL_HISTORY B
    WHERE A.CAR_ID = B.CAR_ID
    AND B.START_DATE <= '2022-11-30'
    AND B.END_DATE >= '2022-11-01'
)
AND TRUNCATE(A.DAILY_FEE * 30 * (1 - C.DISCOUNT_RATE / 100), 0) >= 500000 AND TRUNCATE(A.DAILY_FEE * 30 * (1 - C.DISCOUNT_RATE / 100), 0) < 2000000
ORDER BY FEE DESC, A.CAR_TYPE, A.CAR_ID DESC;
